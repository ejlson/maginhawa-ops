// Builds index.html: the page template + the tested engine from packages/core + the UI.
// Run from the repo root: npm run build:report-builder
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));

const engine = await build({
  entryPoints: [here('../../packages/core/src/report-definition.ts')],
  bundle: true,
  format: 'iife',
  globalName: 'RD',
  target: 'es2020',
  write: false,
  legalComments: 'none',
});

const [page, app] = await Promise.all([readFile(here('src/page.html'), 'utf8'), readFile(here('src/app.js'), 'utf8')]);
const banner = '/* Generated by design/report-builder/build.mjs. Edit src/ or packages/core, not this file. */\n';
// Function replacers, so "$" in the code is never read as a replacement pattern.
const out = page
  .replace('/*ENGINE*/', () => banner + engine.outputFiles[0].text)
  .replace('/*APP*/', () => banner + app);

await writeFile(here('index.html'), out);
console.log(`Built design/report-builder/index.html (${(out.length / 1024).toFixed(0)} KB)`);
